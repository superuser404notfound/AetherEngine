/// AE#956: `LoadOptions.skipsContainerAttachments` opens a Matroska source without reading its
/// attached files, through FFmpegBuild's `skip_attachments` matroska option. The session's probe
/// demuxer reads them unless the option is set; every side reader and reopen skips them.
///
/// Fixture: a 6.5 KB Matroska written by mkvmerge (attachments before the first Cluster, the
/// layout that costs the open the most) with one video stream, one ASS stream and two font
/// attachments. Regenerate with:
///
///     ffmpeg -f lavfi -i color=c=black:s=16x16:r=1:d=1 -c:v libx264 -preset ultrafast -crf 51 \
///       -pix_fmt yuv420p -bsf:v filter_units=remove_types=6 v.mkv
///     printf '1\n00:00:00,000 --> 00:00:01,000\nline\n' > s.srt && ffmpeg -i s.srt s.ass
///     printf 'AE956-FONT-A' > a.ttf && printf 'AE956-FONT-B-OTF' > b.otf
///     mkvmerge --no-date --disable-track-statistics-tags -o fonts.mkv v.mkv s.ass \
///       --attachment-mime-type font/ttf --attach-file a.ttf \
///       --attachment-mime-type font/otf --attach-file b.otf
///
/// Stream layout: 0 = h264 video, 1 = ass, 2 = a.ttf, 3 = b.otf.
struct Issue956SkipAttachmentsTests {

    private func open(_ profile: DemuxerOpenProfile, viaFile: Bool) throws -> (Demuxer, URL?) {
        guard let data = Data(base64Encoded: Self.base64.joined()) else {
            throw CocoaError(.fileReadCorruptFile)
        }
        let demuxer = Demuxer()
        if viaFile {
            let url = FileManager.default.temporaryDirectory
                .appendingPathComponent("ae956-\(UUID().uuidString).mkv")
            try data.write(to: url)
            try demuxer.open(url: url, profile: profile)
            return (demuxer, url)
        }
        try demuxer.open(reader: DataIOReader(data: data), formatHint: "matroska", profile: profile)
        return (demuxer, nil)
    }

    @Test(arguments: [false, true])
    func playbackProfileReadsTheFonts(viaFile: Bool) throws {
        let (demuxer, url) = try open(.playback, viaFile: viaFile)
        defer { demuxer.close(); url.map { try? FileManager.default.removeItem(at: $0) } }
        let fonts = demuxer.fontAttachmentInfos()
        #expect(fonts.map(\.filename) == ["a.ttf", "b.otf"])
        #expect(fonts.first?.data == Data("AE956-FONT-A".utf8))
    }

    @Test(arguments: [false, true])
    func skippingProfileOpensWithoutThemAndKeepsTheTracks(viaFile: Bool) throws {
        let (demuxer, url) = try open(.playback.skippingAttachments(), viaFile: viaFile)
        defer { demuxer.close(); url.map { try? FileManager.default.removeItem(at: $0) } }
        #expect(demuxer.fontAttachmentInfos().isEmpty)
        #expect(demuxer.stream(at: 0)?.pointee.codecpar.pointee.codec_type == AVMEDIA_TYPE_VIDEO)
        #expect(demuxer.stream(at: 1)?.pointee.codecpar.pointee.codec_type == AVMEDIA_TYPE_SUBTITLE)
        #expect(demuxer.stream(at: 2) == nil)
    }

    /// Only the session's probe open reads attachments; the readers that never surface them skip.
    @Test func sideProfilesSkipAndThePlaybackProfileReads() {
        #expect(!DemuxerOpenProfile.playback.skipsAttachments)
        #expect(DemuxerOpenProfile.stillExtraction.skipsAttachments)
        #expect(DemuxerOpenProfile.iFrameSideDemuxer.skipsAttachments)
        #expect(DemuxerOpenProfile.restartReopen.skipsAttachments)
        #expect(DemuxerOpenProfile.subtitleSideDemuxer(callerProbesize: nil, callerMaxAnalyzeDuration: nil).skipsAttachments)
        #expect(DemuxerOpenProfile.atmosConfirmationDemuxer(callerProbesize: nil, callerMaxAnalyzeDuration: nil).skipsAttachments)
        #expect(DemuxerOpenProfile.dolbyVisionRecordAuditDemuxer(callerProbesize: nil, callerMaxAnalyzeDuration: nil).skipsAttachments)
        #expect(!DemuxerOpenProfile.playback.skippingAttachments(false).skipsAttachments)
        #expect(!LoadOptions().skipsContainerAttachments)
    }

